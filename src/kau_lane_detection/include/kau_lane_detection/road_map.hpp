// ====================================================================
// road_map.hpp
//
// 이 맵의 차선 정보. 전역 선언.
//
// 검출 코드가 "차로 폭" 이라는 숫자 하나만 들고 있으면, 선을
// 하나만 잡았을 때 그것이 어느 선인지 알 방법이 없다. 도로
// 단면이 어떻게 생겼는지 — 몇 차로이고, 선이 몇 개이고, 각
// 선이 중앙선에서 얼마나 떨어져 있고, 무슨 색인지 — 를 먼저
// 선언해 두어야 관측 하나를 단면 위의 한 자리에 앉힐 수 있다.
//
// --------------------------------------------------------------------
// 근거 — 맵 mesh 실측
//
// /opt/physicar/src/physicar-sim/share/meshes/
//   custom_71e69ee938032295503bfed557fde18c/*.dae
//
// 삼각형을 x = 6.0 m 평면으로 잘라 단면을 냈다 (단위 m):
//
//   road   y 0.8805 .. 1.5805    아스팔트   폭 0.700
//   ol     y 0.8805 .. 0.9555    흰 실선    폭 0.075
//   cl     y 1.2180 .. 1.2430    황색 점선  폭 0.025
//   il     y 1.5055 .. 1.5805    흰 실선    폭 0.075
//
//   ol 중심 0.9180   cl 중심 1.2305   il 중심 1.5430
//   -> 인접 선 중심 간격 0.3125 m, 흰선끼리 0.6250 m
//
// x = 3.0 / 9.0 단면에서도 같은 값이 나온다. DAE 는 meter 단위
// 이고 visual_scene / SDF / world 어디에도 scale 이 없다.
//
// --------------------------------------------------------------------
// 위상 — 닫힌 순환 트랙
//
// 같은 x = 6.0 평면이 도로를 두 번 지난다. 두 통과의 선 순서가
// 서로 뒤집혀 있다 (y 증가 방향으로 읽어서):
//
//   아래쪽 통과   ol 0.9180  ->  cl 1.2305  ->  il 1.5430
//   위쪽 통과     il 4.2988  ->  cl         ->  ol 4.9590
//
// il 이 양쪽에서 모두 안쪽을 향한다. 즉 도로는 고리(annulus)
// 이고, ol 이 바깥 경계, il 이 안쪽 경계다. 시작점으로 되돌아
// 오는 무한 루프이지 왕복 도로가 아니다.
//
// 그래서 "ol = 왼쪽 선" 같은 이름은 성립하지 않는다. 루프를
// 어느 방향으로 도느냐에 따라 바깥 경계가 차량의 왼쪽에 올
// 수도 오른쪽에 올 수도 있다. 아래 LINES 는 트랙 좌표가 아니라
// 차량 좌표(오른쪽이 +)로 적는다. 그 안에서는 방향과 무관하게
// "중앙선 왼쪽 흰선 / 중앙선 / 오른쪽 흰선" 이 항상 성립한다.
//
// (이 맵을 도는 방향은 전체적으로 좌회전이다 — 즉 루프를
//  반시계로 돈다. 하지만 그 사실이 이 파일에 들어올 자리는
//  없다. LINES 가 이미 차량 좌표로 적혀 있어서 트랙을 도는
//  방향과 무관하게 성립하기 때문이다. 방향은 global/local
//  path planner 쪽 문제이지 단면 선언의 문제가 아니다.)
//
// 영상 검증: 직선 구간 한 프레임을 undistort 해 지면으로
// 역투영하면 (h = 14.65 cm)
//
//   도로 바깥 가장자리 간격  70.0 cm -> h 14.552
//   흰선 안쪽 가장자리 간격  55.0 cm -> h 14.670
//   중앙선 <-> 왼쪽 흰선 안쪽 27.5 cm -> h 14.708
//   중앙선 <-> 오른쪽 흰선 안쪽 27.5 cm -> h 14.633
//
// 같은 프레임 BEV 에서 흰선 사이 간격 195.0 px, sx 0.3220 cm/px
// -> 62.79 cm. mesh 실측 62.50 과 0.5% 차이.
//
// --------------------------------------------------------------------
// 다른 맵으로 옮길 때
//
// 이 파일만 고치면 된다. 차선 수가 3 이상이면 LINES 에 경계선을
// 추가한다. 판정 코드는 LINES 를 훑을 뿐 개수를 가정하지 않는다.
// ====================================================================

#ifndef KAU_LANE_DETECTION__ROAD_MAP_HPP_
#define KAU_LANE_DETECTION__ROAD_MAP_HPP_

#include <cstddef>


namespace kau_road
{

// 선의 색/모양. 검출기가 노란 마스크로 잡았는지 흰 마스크로
// 잡았는지와 대응시켜, 관측을 단면의 후보로 좁히는 데 쓴다.
enum class LineType
{
    White,      // 흰 실선
    Yellow      // 황색 (이 맵은 점선)
};


// 도로 단면의 선 하나.
//
//   offset_cm : 중앙선 기준 횡거리. 차량 오른쪽이 +.
struct LaneLine
{
    double offset_cm;

    LineType type;

    const char * name;
};


// ----------------------------------------------------------------
// 이 맵: 닫힌 루프 2차선
//
// 차량 좌표계 단면 (차량 오른쪽이 +):
//
//   -31.25 cm   흰 실선     왼쪽 도로 경계
//     0.00 cm   황색 점선   중앙선  <- 원점이자 유일한 추종 목표
//   +31.25 cm   흰 실선     오른쪽 도로 경계
//
// 흰선은 차선 경계가 아니라 도로의 양 경계다. 도로 안쪽의
// 유일한 경계가 중앙선이므로, 차선은 중앙선 좌우로 하나씩뿐이다.
//
// 두 흰선 중 어느 쪽이 트랙의 바깥 경계(ol)이고 어느 쪽이
// 안쪽 경계(il)인지는 루프를 도는 방향에 달렸다. 영상만으로는
// 알 수 없고, 알 필요도 없다. 검출에 쓰이는 것은 차량 기준
// 좌/우뿐이다.
//
// ----------------------------------------------------------------
// 지정 차선을 두지 않는다
//
// 예전에는 여기에 "차로 번호"(중앙선 좌/우 중 어느 쪽이 지정
// 차선인가, DRIVE_ON_RIGHT)를 선언해서 자차가 지정 차선을
// 지키는지 판정했다. 지금은 그 판정 자체를 없앤다 — 자차가
// 중앙선 왼쪽 차선에 있든 오른쪽 차선에 있든 상관하지 않고,
// 중앙선(황색 점선)을 그대로 추종 목표로 삼는다.
//
// 그래서 LINES 에 남는 것은 "이 선이 단면의 어디에 있는가"
// 뿐이다. 이건 여전히 필요하다 — 흰선 하나만 보일 때 그게
// 왼쪽 경계인지 오른쪽 경계인지, 즉 중앙선이 거기서 어느
// 쪽으로 31.25 cm 떨어져 있는지를 알아내는 데 쓴다
// (kau_lane_detection_node.hpp 의 identifyLine 참고). 차로
// 번호를 매기는 데는 더 이상 쓰이지 않는다.
// ----------------------------------------------------------------

inline constexpr int LANE_COUNT = 2;

// 2026-08-25: 실차 트랙 실측으로 확정. 이전 값(31.25 / 62.50)은
// 시뮬 mesh 실측이었다.
//
//   흰선 안쪽 간격        56.0 cm
//   흰선 폭                7.4 cm
//   -> 흰선 중심 <-> 중심  56.0 + 7.4 = 63.4 cm
//   -> 차로 폭             63.4 / 2   = 31.7 cm
//
// 시뮬 mesh(31.25 / 62.50)와는 1.44% 다르지만 양쪽에 같은 값을
// 쓴다. 이 상수가 걸리는 게이트 중 가장 빡빡한 것이 축척 불일치
// 경고의 +-15% 라 10배 여유이고, 회랑(+-40%) / 중심선 이탈(30%) /
// 좌우 판정(40%) 은 그보다 더 넓다. constexpr 이라 플랫폼별로
// 나눌 수도 없으므로, 배포 대상인 실차 값으로 통일한다.
//
// 이전에 "실차 실측치가 서로 안 맞아 보류" 로 남아 있던 것은
// 56 을 아스팔트 총 폭으로, 흰선 폭을 5.6 으로 잘못 적었기
// 때문이었다. 56 은 흰선 **안쪽 간격**이고 폭은 7.4 다.

// 인접 선 중심 사이 거리 [cm] = 차로 폭
inline constexpr double LANE_WIDTH_CM = 31.7;

// 흰선 중심 <-> 흰선 중심 [cm] = 도로 폭
inline constexpr double ROAD_WIDTH_CM = 63.4;


inline constexpr LaneLine LINES[] =
{
    { -LANE_WIDTH_CM, LineType::White,  "left road edge"  },
    {           0.0,  LineType::Yellow, "center line"     },
    { +LANE_WIDTH_CM, LineType::White,  "right road edge" }
};

inline constexpr std::size_t LINE_COUNT =
    sizeof(LINES) / sizeof(LINES[0]);


// 도로 반폭 [cm]. 중앙선에서 한쪽 흰선까지.
//
// 관측이 중앙선에서 이보다 멀리 나오면 기준선을 잘못 잡은
// 것이다 (도로 밖 물체를 중앙선으로 착각) — 판정 코드의
// 상한 검사용.
inline constexpr double roadHalfWidthCm()
{
    return 0.5 * ROAD_WIDTH_CM;
}

}  // namespace kau_road

#endif  // KAU_LANE_DETECTION__ROAD_MAP_HPP_